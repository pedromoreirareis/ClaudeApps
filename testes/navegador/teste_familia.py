def servir_pasta(ctx, pasta, host_url):
    """serve uma pasta inteira num endereço (ex.: o app anterior, ou o site de teste)"""
    def h(route):
        u = route.request.url.split('?')[0]
        caminho = u[len(host_url):] or 'index.html'
        if caminho.endswith('/'): caminho += 'index.html'
        if caminho=='nuvem-config.js': return route.fallback()
        arq = os.path.join(pasta, caminho)
        if not os.path.isfile(arq): return route.fulfill(status=404, body='')
        tipo = 'text/html' if arq.endswith('.html') else ('application/javascript' if arq.endswith('.js') else 'application/octet-stream')
        route.fulfill(status=200, content_type=tipo+'; charset=utf-8', body=open(arq,'rb').read(), headers={'Cache-Control':'no-store'})
    ctx.route(host_url+'**', h)

